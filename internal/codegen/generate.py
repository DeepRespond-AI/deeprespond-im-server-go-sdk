    @staticmethod
    def represent(gt: GT, schema: dict[str, Any], required: bool, mode: str) -> tuple[GT, str]:
        """可选的参数怎样表示：返回 (Go 类型, 省略的规则 always/nonzero/ptr/field)。

        mode：patch（修改接口的请求体顶层）、body、query、positional。
        """
        if schema.get("x-drim-three-state"):
            return GT("field", f"Field[{gt.expr}]", elem=gt), "field"
        if required:
            return gt, "always"
        kind = gt.kind
        if kind in ("str", "date"):
            return (GT(kind, "*string", ptr=True), "ptr") if mode == "patch" else (gt, "nonzero")
        if kind == "bool":
            if mode == "query" or mode == "patch" or schema.get("default") is True:
                return GT("bool", "*bool", ptr=True), "ptr"
            return gt, "nonzero"
        if kind == "int":
            if mode != "patch":
                # limit、max_members（创建时）：0 为不给
                return gt, "nonzero"
            return GT("int", "*int", ptr=True), "ptr"
        if kind == "int64":
            return GT("int64", "*int64", ptr=True), "ptr"
        if kind == "float":
            return GT("float", "*float64", ptr=True), "ptr"
        if kind == "struct":
            return GT("struct", "*" + gt.expr, name=gt.name, ptr=True), "ptr"
        return gt, "nonzero"  # time、raw、slice、map、fieldmap

    def input_def(self, name: str, schema: dict[str, Any], mode: str = "body") -> None:
        if name in self.inputs or name in self.building:
            return
        self.building.add(name)
        definition = InputDef(name, schema.get("description", ""))
        required = set(schema.get("required") or [])
        for json_name, prop in (schema.get("properties") or {}).items():
            base = self.inp(prop, name, json_name, mode)
            gt, rule = self.represent(base, prop, json_name in required, mode)
            definition.fields.append((FieldDef(pascal(json_name), json_name, gt, json_name in required, prop), rule))
        self.inputs[name] = definition
        self.input_order.append(name)
        self.building.discard(name)

