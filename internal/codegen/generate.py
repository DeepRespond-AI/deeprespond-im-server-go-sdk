    def render_endpoints(self, ops: list[dict[str, Any]]) -> str:
        out = [HEADER, "package endpoints\n\n", 'import "time"\n\n']
        out.append("var _ = time.Second\n\n")
        names = []
        for op in ops:
            var = pascal(op["operationId"])
            names.append(var)
            out.append(comment(f"{op.get('summary', '')}：{op['_method']} {op['_path']}", prefix=var))
            parts = [
                f"Name: {go_string(op['operationId'])}",
                f"Method: {go_string(op['_method'])}",
                f"Path: {go_string(op['_path'])}",
                f"Category: {pascal(op['x-drim-category'])}",
            ]
            if op.get("x-drim-unsafe-if"):
                parts.append(f"UnsafeIf: {go_string(op['x-drim-unsafe-if'])}")
            if op.get("x-drim-idempotency-key"):
                parts.append(f"IdempotencyKey: {go_string(op['x-drim-idempotency-key'])}")
            if op.get("x-drim-empty-body") or (op.get("requestBody") and not op["requestBody"].get("required", True)):
                parts.append("EmptyBody: true")
            if op.get("x-drim-timeout"):
                parts.append(f"Timeout: {int(op['x-drim-timeout'])} * time.Second")
            if op.get("x-drim-rate-group"):
                parts.append(f"RateGroup: {go_string(op['x-drim-rate-group'])}")
            batch = op.get("x-drim-batch")
            if batch:
                parts.append(f"BatchField: {go_string(batch['field'])}")
                parts.append(f"BatchMax: {int(batch['max'])}")
                if batch.get("charged"):
                    parts.append("BatchCharged: true")
            status = op.get("x-drim-status") or {}
            for code, flag in status.items():
                if flag == "duplicate":
                    parts.append(f"DuplicateStatus: {int(code)}")
            pagination = op.get("x-drim-pagination") or {}
            if pagination.get("style"):
                parts.append(f"Pagination: {go_string(pagination['style'])}")
            if pagination.get("end_empty_string"):
                parts.append("EndEmptyString: true")
            for key, go in (("version", "VersionField"), ("count", "CountField"), ("max_count", "MaxCountField")):
                if pagination.get(key):
                    parts.append(f"{go}: {go_string(pagination[key])}")
            if op.get("x-drim-postprocess"):
                parts.append(f"Postprocess: {go_string(op['x-drim-postprocess'])}")
            code, schema = self.response_schema(op)
            if schema is not None:
                parts.append("HasResult: true")
            if op.get("x-drim-internal"):
                parts.append("Internal: true")
            out.append(f"var {var} = Endpoint{{\n\t" + ",\n\t".join(parts) + ",\n}\n\n")
        out.append("// All 是全部接口，按路径排列。\n")
        out.append("var All = []*Endpoint{\n" + "".join(f"\t&{n},\n" for n in names) + "}\n")
        return "".join(out)

