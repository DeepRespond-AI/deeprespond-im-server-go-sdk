class Generator:
    def __init__(self, spec: dict[str, Any], callback: dict[str, Any] | None) -> None:
        self.spec = spec
        self.callback = callback
        raw_schemas = spec["components"]["schemas"]
        self.schemas = {name: self.flatten(schema, raw_schemas) for name, schema in raw_schemas.items()}
        self.models: dict[str, ModelDef] = {}
        self.model_order: list[str] = []
        self.inputs: dict[str, InputDef] = {}
        self.input_order: list[str] = []
        self.params: dict[str, InputDef] = {}
        self.params_order: list[str] = []
