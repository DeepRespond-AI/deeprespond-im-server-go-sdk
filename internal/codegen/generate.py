    @staticmethod
    def kind_of(schema: dict[str, Any]) -> tuple[str | None, bool]:
        kind = schema.get("type")
        nullable = False
        if isinstance(kind, list):
            nullable = "null" in kind
            rest = [k for k in kind if k != "null"]
            kind = rest[0] if rest else None
        return kind, nullable

    @staticmethod
    def unwrap_oneof(schema: dict[str, Any]) -> tuple[dict[str, Any], bool]:
        for key in ("oneOf", "anyOf"):
            if key in schema:
                options = schema[key]
                nulls = [o for o in options if o.get("type") == "null"]
                others = [o for o in options if o.get("type") != "null"]
                if len(others) == 1:
                    merged = dict(others[0])
                    for extra in ("description",):
                        if extra in schema and extra not in merged:
                            merged[extra] = schema[extra]
                    return merged, bool(nulls)
                return {"x-drim-free-form": True, "type": "object"}, bool(nulls)
        return schema, False

