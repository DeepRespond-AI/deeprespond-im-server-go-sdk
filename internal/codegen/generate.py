def split_words(name: str) -> list[str]:
    return [p for p in re.split(r"[_.\-\s/]+", name) if p]


def pascal(name: str) -> str:
    return "".join(INITIALISMS.get(p.lower(), p[:1].upper() + p[1:]) for p in split_words(name))


def lower_camel(name: str) -> str:
    parts = split_words(name)
    if not parts:
        return name
    first = parts[0].lower()
    text = first + "".join(INITIALISMS.get(p.lower(), p[:1].upper() + p[1:]) for p in parts[1:])
    if text in GO_KEYWORDS:
        text += "_"
    return text


def comment(text: str | None, indent: str = "", prefix: str = "") -> str:
    """Go 的注释：每行加 //，第一行可以带上名字前缀。"""
    lines: list[str] = []
    for part in (text or "").strip().splitlines():
        lines.append(part.rstrip())
    if not lines:
        return ""
    if prefix:
        lines[0] = f"{prefix} {lines[0]}" if lines[0] else prefix
    return "".join(f"{indent}// {line}\n" if line else f"{indent}//\n" for line in lines)


def go_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


